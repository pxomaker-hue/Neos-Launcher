const fs=require('node:fs'),assert=require('node:assert/strict');
const js=fs.readFileSync(process.argv[2],'utf8');
const start=js.indexOf('  function taskMatchesView('),end=js.indexOf('  function groupwareModule(',start);
assert.ok(start>=0&&end>start);
const match=new Function(js.slice(start,end)+'return taskMatchesView;')();
const now=new Date(2026,10,13,12);
assert.equal(match({dueDate:'2026-11-13'},'today',now),true);
assert.equal(match({dueDate:'2026-11-12'},'overdue',now),true);
assert.equal(match({dueDate:'2026-11-13'},'overdue',now),false);
assert.equal(match({dueDate:'2026-11-14'},'upcoming',now),true);
assert.equal(match({dueDate:'2026-11-20'},'upcoming',now),true);
assert.equal(match({dueDate:'2026-11-21'},'upcoming',now),false);
assert.equal(match({},'undated',now),true);
assert.equal(match({due:'invalid'},'today',now),false);
for(const view of ['today','overdue','upcoming','undated'])assert.equal(match({done:true,dueDate:'2026-11-13'},view,now),false);
assert.equal(match({done:true},'done',now),true);
assert.equal(match({done:true},'all',now),true);
assert.equal(match({dueDate:'2027-01-02'},'upcoming',new Date(2026,11,30,12)),true);
console.log('Deadline views: local dates, completed tasks and date boundaries passed');
